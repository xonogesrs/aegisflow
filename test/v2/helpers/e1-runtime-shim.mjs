/**
 * Byte shape of the generated CJS worker bootstrap (spawned legs): registers
 * the SAME resolve redirect through the CJS require surface, then dynamic-
 * imports the payload module (calling its main() when present). Failure of
 * the payload is surfaced via exit(1) — a worker never dies silently.
 */
function bootstrapModuleSource() {
  return `// generated by test/v2/helpers/e1-runtime-shim.mjs — worker bootstrap
const { registerHooks } = require("node:module");
registerHooks({
  resolve(specifier, context, nextResolve) {
    const s = String(specifier);
    if (s.endsWith("colima-runtime.mjs") && !s.includes("${SHIM_TOKEN}")) {
      return { url: process.env.E1_SHIM_URL, shortCircuit: true };
    }
    return nextResolve(specifier, context);
  },
});
// With ` + "`--import <bootstrap>`" + ` the payload script is process.argv[1];
// argv[2]+ are the payload's own arguments (never the payload path).
const payload = process.argv[1];
import(payload).then((m) => (typeof m.main === "function" ? m.main() : undefined)).catch((e) => { console.error(e); process.exit(1); });
`;
}

/**
 * Write the per-run isolation shim set into a fresh disposable directory.
 *
 * @param {string} dir — pre-existing disposable directory (mkdtemp-owned).
 * @returns {{ dir, shimPath, shimUrl, bootstrapPath, bootstrapUrl }}
 */
export function writeIsolatedShim(dir) {
  const shimPath = join(dir, `${SHIM_TOKEN}.mjs`);
  const bootstrapPath = join(dir, "e1-worker-bootstrap.cjs");
  writeFileSync(shimPath, shimModuleSource());
  writeFileSync(bootstrapPath, bootstrapModuleSource());
  return {
    dir,
    shimPath,
    shimUrl: pathToFileURL(shimPath).href,
    bootstrapPath,
    bootstrapUrl: pathToFileURL(bootstrapPath).href,
  };
}

/**
 * The in-process resolve-hook object (module.registerHooks shape). Redirects
 * every "colima-runtime.mjs" specifier (except the shim's own self-reference)
 * to the generated shim — installed before the static tree links.
 *
 * @param {{ shimUrl: string }} opts
 * @returns {{ resolve(specifier, context, nextResolve) }}
 */
export function runtimeShimHooks({ shimUrl }) {
  if (typeof shimUrl !== "string" || shimUrl.length === 0) {
    throw new TypeError("runtimeShimHooks: shimUrl required");
  }
  return {
    resolve(specifier, context, nextResolve) {
      const s = String(specifier);
      if (s.endsWith("colima-runtime.mjs") && !s.includes(SHIM_TOKEN)) {
        return { url: shimUrl, shortCircuit: true };
      }
      return nextResolve(specifier, context);
    },
  };
}

/**
 * Convenience: fresh shim dir under the OS temp (per-run, mkdtemp-random).
 * @returns {{ dir, shimPath, shimUrl, bootstrapPath, bootstrapUrl }}
 */
export function makeShimDir() {
  return writeIsolatedShim(mkdtempSync(join(tmpdir(), "e1-shim-module-")));
}


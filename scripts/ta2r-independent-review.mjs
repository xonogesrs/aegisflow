#!/usr/bin/env node
// scripts/ta2r-independent-review.mjs
//
// TA-2R independent review（deterministic, local, machine cross-check）:
// independently recomputes the machine-verifiable claims of the repair
// generation — verification 20/20, sample admission ids re-derivable,
// schema additive-only, matrix/risk-signal parity, the NEG suite accounting,
// the MANDATORY production gate（non-bypassability）and the content-identity
// delta attribution（baseline pathShas / unattributable=[]）.
//
// Also regenerates ta2r-sample-admissions.json through the PRODUCTION
// classifier（deterministic; ids re-derivable — IR-2）.
//
// Run: node scripts/ta2r-independent-review.mjs
// Local-only, deterministic, no network, no commit/push/seal.

import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, "..");
const OUT = join(REPO, "docs", "pi-graph-output", "ta2r");
const TA1 = join(REPO, "docs", "pi-graph-output", "ta1");

const sha256 = (s) => createHash("sha256").update(String(s)).digest("hex");
const canonical = (v) => {
  const sort = (x) => {
    if (Array.isArray(x)) return x.map(sort);
    if (x && typeof x === "object") return Object.fromEntries(Object.keys(x).sort().map((k) => [k, sort(x[k])]));
    return x;
  };
  return JSON.stringify(sort(v));
};

const checks = [];
const check = (id, ok, detail) => checks.push({ id, ok: Boolean(ok), detail });

// ── IR-1: verification 20/20（ta2r-verification.json）────────────────────
let verification = null;
const vPath = join(OUT, "ta2r-verification.json");
if (existsSync(vPath)) verification = JSON.parse(readFileSync(vPath, "utf8"));
check("IR-1.verification_ok", verification !== null && verification.ok === true, verification ? `ta2r-verify ${verification.passed}/${verification.total}` : "ta2r-verification.json missing");

// ── IR-2: sample admission ids deterministic（production classifier）───────
const samples = [];
{
  const { classify, scanRiskSignals } = await import("../src/admission/classify.mjs");
  const { buildAdmissionRecord } = await import("../src/admission/policy-projection.mjs");
  const { freezeAdmission, deriveAdmissionId, validateAdmission } = await import("../src/admission/admission-record.mjs");
  const FULL = {
    affected_files: { score: 1, reasons: ["single README file"] }, affected_subsystems: { score: 0, reasons: ["docs only"] },
    dependency_depth: { score: 0, reasons: ["no deps"] }, ambiguity: { score: 0, reasons: ["exact text"] },
    expected_execution_steps: { score: 0, reasons: ["one edit"] }, verification_burden: { score: 0, reasons: ["no tests"] },
    external_dependencies: { score: 0, reasons: ["none"] }, concurrency_potential: { score: 0, reasons: ["none"] },
    statefulness: { score: 0, reasons: ["stateless"] }, rollback_complexity: { score: 0, reasons: ["revert 1 file"] },
  };
  const fixtures = [
    ["TA2R-EX-FASTPATH", FULL, "fix one typo in README", ["docs/"]],
    ["TA2R-EX-MEDIUM", { ...FULL, affected_subsystems: { score: 3, reasons: ["two modules + shared helper"] }, ambiguity: { score: 2, reasons: ["vague requirement"] } }, "update the shared helper and add unit tests for two modules", ["src/", "test/"]],
    ["TA2R-EX-HIGH", { ...FULL, affected_files: { score: 3, reasons: ["multi-file refactor"] }, statefulness: { score: 3, reasons: ["in-memory cache"] } }, "refactor the scheduler to persist run state across restarts", ["src/"]],
    ["TA2R-EX-CRITICAL", { ...FULL, affected_files: { score: 1, reasons: ["one statement"] } }, "delete one row from the production database", ["db/"]],
  ];
  for (const [taskId, dims, statement, scope] of fixtures) {
    const c = classify({ dimensionScores: dims, riskSignals: scanRiskSignals(statement) });
    const raw = buildAdmissionRecord({ taskId, classification: c, mutationScope: scope });
    const rec = freezeAdmission(raw);
    const rederived = deriveAdmissionId(rec);
    const valid = validateAdmission(rec).ok;
    samples.push({ taskId, size: rec.size, risk: rec.risk, profile: rec.profile, admission_id: rec.admission_id, rederives: rederived === rec.admission_id, valid });
  }
  const allRedrive = samples.every((s) => s.rederives && s.valid);
  check("IR-2.sample_ids_deterministic", samples.length >= 4 && allRedrive, `${samples.length} samples; ids re-derive + validate`);
  mkdirSync(OUT, { recursive: true });
  writeFileSync(join(OUT, "ta2r-sample-admissions.json"), JSON.stringify({
    schema: "autoloop.sample-admissions/v1",
    card: "AUTOLOOP-TA2",
    generation: "TA-2R",
    generatedAt: new Date().toISOString(),
    note: "Sample admission records generated by the PRODUCTION classifier (src/admission/*) during TA-2R independent review — machine-validated; admission_id derived deterministically.",
    examples: samples,
  }, null, 2) + "\n");
}

// ── IR-3: schema additive-only（vs TA-1）──────────────────────────────────
{
  const { ADMISSION_SCHEMA_DEFINITION } = await import("../src/admission/admission-record.mjs");
  let ok = true, detail = "";
  try {
    const ta1Schema = JSON.parse(readFileSync(join(TA1, "ta1-admission-schema.json"), "utf8"));
    const baseProps = new Set(Object.keys(ta1Schema.properties));
    const prodProps = Object.keys(ADMISSION_SCHEMA_DEFINITION.properties);
    const missing = [...baseProps].filter((p) => !prodProps.includes(p));
    const additions = prodProps.filter((p) => !baseProps.has(p));
    ok = missing.length === 0 && additions.every((p) => ["mutation_scope", "tool_permissions"].includes(p));
    detail = `missing=${missing.join(",")} additions=${additions.join(",")}`;
  } catch (e) { ok = false; detail = e.message; }
  check("IR-3.schema_additive_only", ok, detail);
}

// ── IR-4: matrix parity ───────────────────────────────────────────────────
{
  const { PROFILE_MATRIX } = await import("../src/admission/policy-projection.mjs");
  let ok = true, detail = "";
  try {
    const dm = JSON.parse(readFileSync(join(TA1, "ta1-admission-decision-matrix.json"), "utf8"));
    for (const row of dm.matrix ?? []) {
      const d = PROFILE_MATRIX[row.profile];
      if (!d) { ok = false; continue; }
      for (const [k, v] of Object.entries(row.decisions)) if (d[k] !== v) { ok = false; detail += `${row.profile}.${k}; `; }
    }
  } catch (e) { ok = false; detail = e.message; }
  check("IR-4.matrix_parity", ok, detail || "7 profiles match");
}

// ── IR-5: risk signal parity（15 canonical signals vs TA-1 model）─────────
{
  const { RISK_SIGNALS } = await import("../src/admission/classify.mjs");
  let ok = false, detail = "";
  try {
    const tm = JSON.parse(readFileSync(join(TA1, "ta1-risk-tier-model.json"), "utf8"));
    const ta1Ids = new Set((tm.riskSignals ?? []).map((s) => s.id));
    const prodIds = new Set((RISK_SIGNALS ?? []).map((s) => s.id));
    const missing = [...ta1Ids].filter((id) => !prodIds.has(id));
    const extra = [...prodIds].filter((id) => !ta1Ids.has(id));
    ok = missing.length === 0 && extra.length === 0;
    detail = `${prodIds.size} signals; missing=${missing.join(",")} extra=${extra.join(",")}`;
  } catch (e) { ok = false; detail = e.message; }
  check("IR-5.risk_signal_parity", ok, detail);
}

// ── IR-6: NEG suite accounting（from the structured verification）─────────
{
  const admission = (verification?.regression ?? []).find((r) => r.suite === "test:admission");
  check("IR-6.neg_suite", admission !== undefined && admission.failed === 0, admission ? `admission suite ${admission.passed}/${admission.tests} pass` : "admission suite missing");
}

// ── IR-7: mandatory production gate（non-bypassability, independent spy）──
{
  const { assertProductionAdmission, runAdmittedGraph } = await import("../src/admission/admission-gate.mjs");
  const { freezeAdmission, validateAdmission } = await import("../src/admission/admission-record.mjs");
  const { classify, scanRiskSignals } = await import("../src/admission/classify.mjs");
  const { buildAdmissionRecord } = await import("../src/admission/policy-projection.mjs");
  const FULL = {
    affected_files: { score: 1, reasons: ["single README file"] }, affected_subsystems: { score: 0, reasons: ["docs only"] },
    dependency_depth: { score: 0, reasons: ["no deps"] }, ambiguity: { score: 0, reasons: ["exact text"] },
    expected_execution_steps: { score: 0, reasons: ["one edit"] }, verification_burden: { score: 0, reasons: ["no tests"] },
    external_dependencies: { score: 0, reasons: ["none"] }, concurrency_potential: { score: 0, reasons: ["none"] },
    statefulness: { score: 0, reasons: ["stateless"] }, rollback_complexity: { score: 0, reasons: ["revert 1 file"] },
  };
  const c = classify({ dimensionScores: FULL, riskSignals: scanRiskSignals("fix one typo in README") });
  const rec = freezeAdmission(buildAdmissionRecord({ taskId: "IR-7", classification: c, mutationScope: ["docs/"] }));
  const calls = [];
  const spy = async (opts) => { calls.push(opts); return { final: "PASS" }; };
  const noAdm = await runAdmittedGraph({ admission: null, runner: spy });
  const tampered = await runAdmittedGraph({ admission: { ...rec, risk: "HIGH" }, runner: spy });
  const valid = await runAdmittedGraph({ admission: rec, runner: spy });
  const ok = noAdm.holdCode === "ADMISSION_REQUIRED" && tampered.holdCode === "ADMISSION_DRIFT"
    && valid.final === "PASS" && calls.length === 1 && calls[0].admission === rec && assertProductionAdmission(null).ok === false;
  check("IR-7.production_gate_nonbypassable", ok, "no admission -> ADMISSION_REQUIRED (spy never invoked); tampered -> ADMISSION_DRIFT; valid -> dispatched unchanged");
}

// ── IR-8: content-identity delta attribution（finding 2）──────────────────
{
  const { collectRepoFacts } = await import("../src/governance/review-bundle.mjs");
  const bPath = join(OUT, "ta2r-card-start-baseline.json");
  if (!existsSync(bPath)) {
    check("IR-8.content_delta_attribution", false, "ta2r-card-start-baseline.json missing");
  } else {
    const bl = JSON.parse(readFileSync(bPath, "utf8"));
    let ok = true, detail = "";
    try {
      const facts = collectRepoFacts(REPO, { baseline: bl });
      const hasShas = bl && typeof bl.pathShas === "object" && Object.keys(bl.pathShas ?? {}).length > 0 && typeof bl.contentDigest === "string";
      ok = hasShas && facts.unattributable.length === 0;
      detail = `baseline pathShas=${Object.keys(bl.pathShas ?? {}).length}; unattributable=${facts.unattributable.length}; delta=${facts.deltaPaths.length} (membership ${facts.membershipDelta.length} + content ${facts.contentModified.length}); content-modified: ${facts.contentModified.slice(0, 6).join(",")}`;
    } catch (e) { ok = false; detail = e.message; }
    check("IR-8.content_delta_attribution", ok, detail);
  }
}

const failed = checks.filter((c) => !c.ok);
const review = {
  schema: "autoloop.ta2-independent-review/v1",
  card: "AUTOLOOP-TA2",
  generation: "TA-2R",
  supersedesBundleIdentity: "432e85b5742b194d24c4558b1eec8f1415dcdc6ee52c2f934eff900f9e0a6272",
  reviewedAt: new Date().toISOString(),
  reviewer: "independent review cross-check (deterministic, local)",
  total: checks.length,
  passed: checks.length - failed.length,
  failed: failed.length,
  ok: failed.length === 0,
  checks,
  blockingFindings: [],
  nonBlockingFindings: [],
  digest: sha256(canonical(checks)),
};
mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, "ta2r-independent-review.json"), JSON.stringify(review, null, 2) + "\n");
console.log(JSON.stringify(review, null, 2));
process.exit(review.ok ? 0 : 1);
